    public static void SetLanguage(string selection)
    {
        SelectedLanguage = selection is "en" or "sk" ? selection : "system";
        _language = SelectedLanguage == "system"
            ? (CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.Equals("sk", StringComparison.OrdinalIgnoreCase) ? "sk" : "en")
            : SelectedLanguage;
    }

    public static string T(string key)
    {
        Dictionary<string, string> source = _language == "sk" ? Slovak : English;
        return source.TryGetValue(key, out string? value) ? value : key;
    }

